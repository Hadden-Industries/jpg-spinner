<# Publishes the English offline notice without a second copy of its prose.
   WinUI/MRT consumes XAML and RESW; .NET's XML reader consumes the same sources
   here. No runtime Markdown parser, browser or network service is required. #>
[CmdletBinding()]
param([switch]$Check)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repositoryRoot = Split-Path -Parent $PSScriptRoot
$shell = [Xml.XmlDocument]::new()
$shell.Load((Join-Path $repositoryRoot 'src/JpgSpinner.App/MainWindow.xaml'))
$resources = [Xml.XmlDocument]::new()
$resources.Load((Join-Path $repositoryRoot 'src/JpgSpinner.App/Strings/en-US/Resources.resw'))
$ns = [Xml.XmlNamespaceManager]::new($shell.NameTable)
$ns.AddNamespace('ui', 'http://schemas.microsoft.com/winfx/2006/xaml/presentation')
$ns.AddNamespace('x', 'http://schemas.microsoft.com/winfx/2006/xaml')
$notice = $shell.SelectSingleNode('//*[@x:Name="PrivacyNoticeContent"]', $ns)
if ($null -eq $notice) { throw 'No packaged privacy notice was found.' }
$paragraphs = [Collections.Generic.List[string]]::new()
foreach ($node in $notice.ChildNodes) {
    if ($node -isnot [Xml.XmlElement]) { continue }
    if ($node.LocalName -cnotin @('TextBlock', 'HyperlinkButton')) { throw 'Unsupported privacy content element.' }
    $uid = $node.GetAttribute('Uid', 'http://schemas.microsoft.com/winfx/2006/xaml')
    $property = if ($node.LocalName -ceq 'HyperlinkButton') { 'Content' } else { 'Text' }
    $value = $resources.SelectSingleNode("/root/data[@name='$uid.$property']/value")
    if ($null -eq $value -or [string]::IsNullOrWhiteSpace($value.InnerText)) { throw "Missing resource: $uid.$property" }
    $text = $value.InnerText
    if ($node.LocalName -ceq 'HyperlinkButton') {
        $uri = [Uri]$node.GetAttribute('NavigateUri')
        if (-not $uri.IsAbsoluteUri -or $uri.Scheme -cne 'https') { throw 'Policy links must use HTTPS.' }
        $text = "[$text]($uri)"
    }
    elseif ($node.GetAttribute('AutomationProperties.HeadingLevel') -ceq 'Level1') { $text = "# $text" }
    elseif ($node.GetAttribute('AutomationProperties.HeadingLevel') -ceq 'Level2') { $text = "## $text" }
    $paragraphs.Add($text)
}
$content = "<!-- Generated by scripts/Export-AppPrivacyNotice.ps1 from the packaged English privacy notice. -->`n`n" +
($paragraphs -join "`n`n") + "`n"
$destination = Join-Path $repositoryRoot 'docs/privacy.md'
if ($Check) {
    if ([IO.File]::ReadAllText($destination).Replace("`r`n", "`n") -cne $content) {
        throw 'docs/privacy.md differs from the app notice. Run scripts/Export-AppPrivacyNotice.ps1.'
    }
    Write-Output 'PASS: published English notice matches the packaged notice.'
}
else {
    [IO.File]::WriteAllText($destination, $content, [Text.UTF8Encoding]::new($false))
}
